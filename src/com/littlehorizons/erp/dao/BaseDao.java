package com.littlehorizons.erp.dao;

import com.littlehorizons.erp.exception.DataAccessException;
import com.littlehorizons.erp.util.DatabaseConnection;
import com.littlehorizons.erp.util.ErrorLogger;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Template for every DAO: opens connections, binds parameters through {@link PreparedStatement},
 * maps rows with lambdas and always releases JDBC resources with try-with-resources.
 * <p>
 * Subclasses only provide SQL, a {@link StatementBinder} and a {@link RowMapper}, so the
 * error handling and logging policy lives in a single place (DRY / Template Method).
 */
public abstract class BaseDao {

    /** Binds the parameters of a prepared statement. */
    @FunctionalInterface
    public interface StatementBinder {
        StatementBinder NONE = statement -> { };

        void bind(PreparedStatement statement) throws SQLException;
    }

    /** Converts the current row of a result set into an object. */
    @FunctionalInterface
    public interface RowMapper<T> {
        T map(ResultSet resultSet) throws SQLException;
    }

    /** Unit of work executed inside a single database transaction. */
    @FunctionalInterface
    public interface TransactionWork<R> {
        R execute(Connection connection) throws SQLException;
    }

    private static final int MYSQL_DUPLICATE_KEY = 1062;
    private static final int MYSQL_FK_PARENT_ROW = 1451;
    private static final int MYSQL_FK_CHILD_ROW = 1452;
    private static final int MYSQL_CHECK_VIOLATION = 3819;

    /** Cache of table existence checks (the schema does not change while the app runs). */
    private static final Map<String, Boolean> TABLE_CACHE = new ConcurrentHashMap<>();

    protected final DatabaseConnection database;
    protected final ErrorLogger logger;

    protected BaseDao(DatabaseConnection database) {
        this.database = database;
        this.logger = ErrorLogger.getInstance();
    }

    // ------------------------------------------------------------------ simple operations

    protected <T> List<T> queryList(String sql, StatementBinder binder, RowMapper<T> mapper) {
        try (Connection connection = database.getConnection()) {
            return queryList(connection, sql, binder, mapper);
        } catch (SQLException e) {
            throw failure("query", sql, e);
        }
    }

    protected <T> Optional<T> queryOne(String sql, StatementBinder binder, RowMapper<T> mapper) {
        List<T> rows = queryList(sql, binder, mapper);
        return rows.isEmpty() ? Optional.empty() : Optional.of(rows.get(0));
    }

    protected long queryCount(String sql, StatementBinder binder) {
        return queryOne(sql, binder, rs -> rs.getLong(1)).orElse(0L);
    }

    protected int executeUpdate(String sql, StatementBinder binder) {
        try (Connection connection = database.getConnection()) {
            return executeUpdate(connection, sql, binder);
        } catch (SQLException e) {
            throw failure("update", sql, e);
        }
    }

    /** Executes an INSERT and returns the AUTO_INCREMENT key generated by MySQL. */
    protected int executeInsert(String sql, StatementBinder binder) {
        try (Connection connection = database.getConnection()) {
            return executeInsert(connection, sql, binder);
        } catch (SQLException e) {
            throw failure("insert", sql, e);
        }
    }

    /**
     * Runs several statements atomically: commits when the work finishes and rolls back
     * when any SQL error or business exception happens.
     */
    protected <R> R inTransaction(String operation, TransactionWork<R> work) {
        try (Connection connection = database.getConnection()) {
            boolean previousAutoCommit = connection.getAutoCommit();
            connection.setAutoCommit(false);
            try {
                R result = work.execute(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException e) {
                connection.rollback();
                throw e;
            } finally {
                connection.setAutoCommit(previousAutoCommit);
            }
        } catch (SQLException e) {
            throw failure(operation, "transaction", e);
        }
    }

    /**
     * True when {@code table} exists in the current database. Used by the optional extension tables
     * (horarios_clase, valores_personalizados) so the application also runs on the official script alone.
     */
    public boolean tableExists(String table) {
        return TABLE_CACHE.computeIfAbsent(table, name -> queryCount(
                "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?",
                ps -> ps.setString(1, name)) > 0);
    }

    // ------------------------------------------------------------------ connection-scoped helpers

    protected <T> List<T> queryList(Connection connection, String sql, StatementBinder binder, RowMapper<T> mapper)
            throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            binder.bind(statement);
            try (ResultSet resultSet = statement.executeQuery()) {
                List<T> rows = new ArrayList<>();
                while (resultSet.next()) {
                    rows.add(mapper.map(resultSet));
                }
                return rows;
            }
        }
    }

    protected int executeUpdate(Connection connection, String sql, StatementBinder binder) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            binder.bind(statement);
            return statement.executeUpdate();
        }
    }

    protected int executeInsert(Connection connection, String sql, StatementBinder binder) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            binder.bind(statement);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                return keys.next() ? keys.getInt(1) : 0;
            }
        }
    }

    // ------------------------------------------------------------------ binding / mapping helpers

    protected static void setNullableString(PreparedStatement statement, int index, String value) throws SQLException {
        if (value == null || value.isBlank()) {
            statement.setNull(index, Types.VARCHAR);
        } else {
            statement.setString(index, value);
        }
    }

    protected static void setNullableInt(PreparedStatement statement, int index, Integer value) throws SQLException {
        if (value == null) {
            statement.setNull(index, Types.INTEGER);
        } else {
            statement.setInt(index, value);
        }
    }

    protected static void setNullableDate(PreparedStatement statement, int index, LocalDate value) throws SQLException {
        if (value == null) {
            statement.setNull(index, Types.DATE);
        } else {
            statement.setDate(index, Date.valueOf(value));
        }
    }

    protected static void setDate(PreparedStatement statement, int index, LocalDate value) throws SQLException {
        statement.setDate(index, Date.valueOf(value));
    }

    protected static LocalDate getLocalDate(ResultSet resultSet, String column) throws SQLException {
        Date date = resultSet.getDate(column);
        return date == null ? null : date.toLocalDate();
    }

    protected static Integer getNullableInt(ResultSet resultSet, String column) throws SQLException {
        int value = resultSet.getInt(column);
        return resultSet.wasNull() ? null : value;
    }

    protected static BigDecimal getMoney(ResultSet resultSet, String column) throws SQLException {
        BigDecimal value = resultSet.getBigDecimal(column);
        return value == null ? BigDecimal.ZERO : value;
    }

    /** SQL expression with the full name of a person table aliased as {@code alias}. */
    protected static String fullName(String alias) {
        return "CONCAT_WS(' ', " + alias + ".primer_nombre, " + alias + ".segundo_nombre, "
                + alias + ".primer_apellido, " + alias + ".segundo_apellido)";
    }

    // ------------------------------------------------------------------ error translation

    /**
     * Logs the technical details in error_log.txt and returns an exception whose message
     * is understandable for the end user.
     */
    protected DataAccessException failure(String operation, String sql, SQLException e) {
        logger.error(getClass().getSimpleName(), "Failed " + operation + " [" + compact(sql) + "] SQLState="
                + e.getSQLState() + " code=" + e.getErrorCode(), e);
        String message = switch (e.getErrorCode()) {
            case MYSQL_DUPLICATE_KEY -> "Ya existe un registro con esos datos únicos (" + extractDuplicate(e) + ").";
            case MYSQL_FK_PARENT_ROW -> "No se puede eliminar: el registro tiene información asociada.";
            case MYSQL_FK_CHILD_ROW -> "El registro relacionado no existe (verifique los identificadores).";
            case MYSQL_CHECK_VIOLATION -> "Los datos no cumplen una restricción de la base de datos.";
            default -> "Error de base de datos al realizar la operación. Detalle registrado en error_log.txt.";
        };
        return new DataAccessException(message, e);
    }

    private static String extractDuplicate(SQLException e) {
        String message = e.getMessage();
        int start = message == null ? -1 : message.indexOf('\'');
        int end = start < 0 ? -1 : message.indexOf('\'', start + 1);
        return start >= 0 && end > start ? "valor " + message.substring(start, end + 1) : "valor duplicado";
    }

    private static String compact(String sql) {
        String oneLine = sql.replaceAll("\\s+", " ").trim();
        return oneLine.length() > 160 ? oneLine.substring(0, 160) + "..." : oneLine;
    }
}
